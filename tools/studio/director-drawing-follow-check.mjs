import assert from 'node:assert/strict';
import {validateDrawing,paintDrawing} from '../../simple-editor/director-drawing.js';
import {sampleMotion} from '../../simple-editor/director-motion.js';
const layer={id:'plain',name:'Sketch',visible:true,locked:false,opacity:1,strokes:[]};
validateDrawing({version:1,layers:[layer]});
const board={version:1,layers:[{...layer,id:'hat',name:'Hat',joint:'Head',jointAnchor:[100,80]},layer]};
validateDrawing(board);
assert.throws(()=>validateDrawing({version:1,layers:[{...layer,joint:''}]}),/joint/);
assert.throws(()=>validateDrawing({version:1,layers:[{...layer,jointAnchor:[1]}]}),/anchor/);
const shifts=[];
const ctx=()=>({globalAlpha:1,globalCompositeOperation:'source-over',fillRect(){},transform(){},save(){},restore(){},drawImage(){},translate(x,y){shifts.push([x,y]);}});
const scratch={getContext:()=>({clearRect(){}})};
paintDrawing({getContext:ctx},board,null,scratch,true,null,{places:{hat:[160,50]}});
assert.deepEqual(shifts,[[60,-30]]);
shifts.length=0;
paintDrawing({getContext:ctx},board,null,scratch,true,null,{places:{plain:[160,50]}});
assert.deepEqual(shifts,[]);
shifts.length=0;
paintDrawing({getContext:ctx},{version:1,layers:[layer]},null,scratch,true,null,{places:{plain:[10,10]}});
assert.deepEqual(shifts,[]);
const posed=sampleMotion(board,6);
assert.equal(posed.layers[0].joint,'Head');assert.deepEqual(posed.layers[0].jointAnchor,[100,80]);assert.equal(posed.layers[1].joint,undefined);
assert.equal(JSON.stringify(board),JSON.stringify({version:1,layers:[{...layer,id:'hat',name:'Hat',joint:'Head',jointAnchor:[100,80]},layer]}));
console.log('Drawing follow checks passed: optional joint, screen-space default, parented shift, untouched source and sampled layer.');
