import assert from 'node:assert/strict';
import {effectCels,celStrokes} from '../../simple-editor/director-cels.js';
import {validateDrawing} from '../../simple-editor/director-drawing.js';
import {sampleMotion} from '../../simple-editor/director-motion.js';
const stroke={tool:'ellipse',color:'#112233',size:3,filled:true,points:[[400,200],[500,300]]};
const layer={id:'a',name:'FX',visible:true,locked:false,opacity:1,strokes:[stroke]};
const original=JSON.stringify(layer);
const smear={...layer,cels:effectCels(layer,5,2,119,{kind:'smear',axis:'x',factor:2})};
assert.equal(JSON.stringify(layer),original);
assert.deepEqual(celStrokes(smear,4),[stroke]);
assert.deepEqual(celStrokes(smear,5)[0].points,[[350,200],[550,300]]);
assert.deepEqual(celStrokes(smear,6),celStrokes(smear,5));
assert.deepEqual(celStrokes(smear,7),[stroke]);
const board={version:1,layers:[smear]};validateDrawing(board);
assert.deepEqual(sampleMotion(board,5).layers[0].strokes,celStrokes(smear,5));
assert.deepEqual(sampleMotion(board,7).layers[0].strokes,[stroke]);
const burst={kind:'impact',x:480,y:270,radius:80,rays:12,color:'#ffcc00',size:4};
const fx={...layer,strokes:[],cels:effectCels({...layer,strokes:[]},8,1,119,burst)};
validateDrawing({version:1,layers:[fx]});assert.equal(celStrokes(fx,8).length,12);assert.deepEqual(celStrokes(fx,9),[]);
const boundary={...layer,cels:[{frame:7,kind:'breakdown',strokes:[],corrections:[]}]};
const result=effectCels(boundary,5,2,119,burst);assert.equal(result.length,2);assert.deepEqual(result[1],boundary.cels[0]);
for(const frame of [5,6])assert.throws(()=>effectCels({...layer,cels:[{frame,kind:'key',strokes:[],corrections:[]}]},5,2,119,burst),/unused/);
assert.throws(()=>effectCels({...layer,locked:true},5,2,119,burst),/Unlock/);
assert.throws(()=>effectCels(layer,118,2,119,burst),/return cel/);
assert.throws(()=>effectCels(layer,5,1.5,119,burst),/1–24/);
assert.throws(()=>effectCels(layer,5,2,119,{...burst,x:0}),/inside/);
assert.throws(()=>effectCels(layer,5,2,119,{...burst,rays:100}),/valid impact/);
assert.throws(()=>effectCels({...layer,strokes:[]},5,2,119,{kind:'smear',axis:'x',factor:2}),/painted/);
assert.throws(()=>effectCels({...layer,strokes:[{...stroke,points:[[0,200],[500,300]]}]},5,2,119,{kind:'smear',axis:'x',factor:4}),/leave/);
const full={...layer,cels:Array.from({length:239},(_,i)=>({frame:100+i,kind:'key',strokes:[],corrections:[]}))};
assert.throws(()=>effectCels(full,5,2,1000,burst),/240/);assert.equal(full.cels.length,239);
console.log('Effect checks passed: editable strokes, exact short holds and return, blank FX layer, sampler integration, protected existing cels, source isolation, bounds, locks and capacity.');
